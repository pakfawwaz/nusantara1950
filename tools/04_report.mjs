// Validation report: integrity checks + per-province sanity tables. Writes DATA_REPORT.md
import fs from 'node:fs';
const rd = f => JSON.parse(fs.readFileSync('public/data/' + f, 'utf8'));
const topo = rd('kecamatan.topo.json'), geo = rd('kecamatan_geo.json'), at = rd('kecamatan_attrs.json'), adm = rd('admin1950.json'), seeds = rd('seeds.json'), ps = rd('popsamples.json');
const P = topo.objects.kec.geometries.map(g => g.properties), n = P.length, ids = geo.ids;
const lines = [], log = s => { lines.push(s); console.log(s); };
const checks = []; const check = (name, ok, extra = '') => { checks.push(ok); log(`- [${ok ? 'x' : ' '}] ${name} ${extra}`); };
const sum = a => a.reduce((s, v) => s + v, 0);
log('# DATA_REPORT (generated by tools/04_report.mjs)\n');
log('## Integrity checks');
const idSet = new Set(ids);
check('ids unique and match topology', idSet.size === n && topo.objects.kec.geometries.every((g, i) => g.properties.id === ids[i]), `(n=${n})`);
for (const k of ['population','urban','literacy','lifeExpectancy','grdp_rp_million','terrain','roadClass','portLevel','laborShare','outputShare','culture']) check(`attrs.${k} length == n`, at[k].length === n);
let asym = 0; geo.neighbors.forEach((nb, i) => nb.forEach(j => { if (!geo.neighbors[j].includes(i)) asym++; })); check('adjacency symmetric', asym === 0, `(asymmetric pairs: ${asym})`);
const regOf = new Map(); adm.regencies.forEach(r => r.kec.forEach(id => regOf.set(id, r.id)));
check('every kecamatan belongs to exactly one regency', regOf.size === n && sum(adm.regencies.map(r => r.kec.length)) === n);
check('every regency capital lies inside its regency', adm.regencies.every(r => regOf.get(r.capital) === r.id));
check('every province capital resolves', adm.provinces.every(p => idSet.has(p.capital)));
check('seed references resolve', [...seeds.resources.map(x => x.kec), ...seeds.ports.map(x => x.kec), ...seeds.industries.map(x => x.kec), ...seeds.rail.flatMap(l => l.path), ...seeds.roads.flatMap(l => l.path)].every(id => idSet.has(id)));
check('rail lines have no broken legs', seeds.rail.every(l => l.brokenLegs === 0));
check('population samples cover every kecamatan', ps.samples.length === n && ps.samples.every(s => s.length >= 9 && s.length % 3 === 0));
check('output shares sum ~10000 per kecamatan', at.outputShare.every(o => Math.abs(sum(o) - 10000) <= 12));
check('labor shares sum ~10000 per kecamatan', at.laborShare.every(o => Math.abs(sum(o) - 10000) <= 12));

const pop = at.population, totalPop = sum(pop);
const w = (arr) => sum(arr.map((v, i) => v * pop[i])) / totalPop;
const agriIdx = [0, 1, 2, 3];
const grdp = at.grdp_rp_million, totalG = sum(grdp);
log('\n## National calibration (target in brackets)');
log(`- Population: ${(totalPop / 1e6).toFixed(2)} M [75]`);
log(`- GDP per capita: Rp ${(totalG * 1e6 / totalPop / 1e6).toFixed(2)} juta (2026 prices) [~9.89]`);
log(`- Urbanisation: ${(100 * w(at.urban)).toFixed(1)} % [12]`);
log(`- Adult literacy: ${(100 * w(at.literacy)).toFixed(1)} % [40]`);
log(`- Mean years of schooling: ${w(at.meanYearsSchooling).toFixed(2)} [1.0]`);
log(`- Life expectancy: ${w(at.lifeExpectancy).toFixed(1)} [40]`);
log(`- Agriculture share of jobs: ${(100 * w(at.laborShare.map(l => sum(agriIdx.map(s => l[s])) / 10000))).toFixed(1)} % [75]`);
log(`- Agriculture share of output: ${(100 * sum(at.outputShare.map((o, i) => sum(agriIdx.map(s => o[s])) / 10000 * grdp[i])) / totalG).toFixed(1)} % [57.5]`);
log(`- Electrification (pop-weighted): ${(100 * w(at.electrification)).toFixed(1)} %`);
log(`- Poverty rate (pop-weighted): ${(100 * w(at.poverty)).toFixed(0)} %`);
log(`- Capital/output ratio: ${(sum(at.capital_rp_million) / totalG).toFixed(2)}`);

log('\n## Per 1950-province summary');
log('| Province | Reg | Kec | Pop (M) | Dens /km² | Urban % | GDPpc (Rp jt) | rel | Lit % | Life | Agri jobs % | Elec % |');
log('|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|');
const natPc = totalG / totalPop; const idx = new Map(ids.map((id, i) => [id, i]));
const rowsByProv = {};
for (const r of adm.regencies) (rowsByProv[r.prov] ??= { reg: 0, k: [] }).reg++ , rowsByProv[r.prov].k.push(...r.kec.map(id => idx.get(id)));
for (const p of adm.provinces) {
  const g = rowsByProv[p.id], ks = g.k, pp = sum(ks.map(i => pop[i])), gg = sum(ks.map(i => grdp[i])), area = sum(ks.map(i => geo.area_km2[i]));
  const wk = a => sum(ks.map(i => a[i] * pop[i])) / pp;
  log(`| ${p.name}${p.locked ? ' (locked)' : ''} | ${g.reg} | ${ks.length} | ${(pp / 1e6).toFixed(2)} | ${(pp / area).toFixed(0)} | ${(100 * wk(at.urban)).toFixed(1)} | ${(gg / pp).toFixed(1)} | ${(gg / pp / natPc).toFixed(2)} | ${(100 * wk(at.literacy)).toFixed(0)} | ${wk(at.lifeExpectancy).toFixed(1)} | ${(100 * wk(at.laborShare.map(l => sum(agriIdx.map(s => l[s])) / 10000))).toFixed(0)} | ${(100 * wk(at.electrification)).toFixed(1)} |`);
}
log('\n## Terrain classes (kecamatan counts) [coastal lowland, lowland, hills, mountains] + swamp flags');
for (const p of adm.provinces) { const ks = rowsByProv[p.id].k; const c = [0, 0, 0, 0]; ks.forEach(i => c[at.terrain[i]]++); log(`- ${p.name}: ${c.join(' / ')}  swamp ${ks.filter(i => at.swamp[i]).length}`); }
log('\n## Largest kecamatan by population');
[...Array(n).keys()].sort((a, b) => pop[b] - pop[a]).slice(0, 12).forEach(i => log(`- ${P[i].name} (${P[i].kab_name}, ${P[i].prov_name}): ${(pop[i] / 1000).toFixed(0)}k, ${(pop[i] / geo.area_km2[i]).toFixed(0)}/km²`));
log('\n## Highest GDP per capita kecamatan (enclaves)');
[...Array(n).keys()].filter(i => pop[i] > 3000).sort((a, b) => grdp[b] / pop[b] - grdp[a] / pop[a]).slice(0, 10).forEach(i => log(`- ${P[i].name} (${P[i].kab_name}): Rp ${(grdp[i] / pop[i]).toFixed(1)} jt (x${(grdp[i] / pop[i] / natPc).toFixed(1)})`));
log('\n## Regency capitals sample (heuristic; review if needed)');
for (const code of ['R32.73','R32.04','R33.08','R35.07','R12.07','R51.08','R16.71','R73.71','R81.71','R64.02','R14.01','R62.01']) { const r = adm.regencies.find(x => x.id === code); if (r) log(`- ${r.name}: ${P[idx.get(r.capital)].name} (${r.kec.length} kec)`); }
log('\n## Provincial capitals');
adm.provinces.forEach(p => log(`- ${p.name}: ${P[idx.get(p.capital)].name} / ${P[idx.get(p.capital)].kab_name}`));
log('\n## Resolved seed counts');
log(`- resources ${seeds.resources.length} (hidden ${seeds.resources.filter(r => r.hidden).length}), rail lines ${seeds.rail.length} (${sum(seeds.rail.map(l => l.stations.length))} stations, ${new Set(seeds.rail.flatMap(l => l.path)).size} kecamatan on track), ports ${seeds.ports.length}, industries ${seeds.industries.length}, trunk-road kecamatan ${new Set(seeds.roads.flatMap(l => l.path)).size}`);
log('\n## File sizes (bytes raw → gzip estimate)');
import zlib from 'node:zlib';
let tot = 0; for (const f of fs.readdirSync('public/data')) { const b = fs.readFileSync('public/data/' + f); const z = zlib.gzipSync(b).length; tot += z; log(`- ${f}: ${b.length} → ${z}`); }
log(`- TOTAL gzip: ${(tot / 1e6).toFixed(2)} MB (budget 15 MB)`);
log(`\n**Checks passed: ${checks.filter(Boolean).length}/${checks.length}**`);
fs.writeFileSync('DATA_REPORT.md', lines.join('\n') + '\n');
process.exit(checks.every(Boolean) ? 0 : 1);
